#!/usr/bin/env python3
"""Generate the osu025 tie cells (osu025_tie.{gds,lef,lib,v}) in this directory.

The OSU 0.25 um library has no tie cells, but ORFS synthesis maps every
constant 0/1 net to one, so any design with constants fails without them.
Both cells are upstream INVX1 with its input strapped to a rail by one extra
metal1 rectangle in INVX1's own pin column (same width, no new spacing):

  TIEHI: A tied to gnd (fills the 0.45 um gap down to the gnd strap) -> Y = 1
  TIELO: A tied to vdd (metal1 up to the vdd strap)                    -> Y = 0

The generated files are tracked; rerun only to regenerate them:
  overlays/osu025/make_tie_cells.py pdks/osu025/osu025_stdcells.gds \
      pdks/osu025/osu025_stdcells.lef \
      pdks/.src/osu025/latest/cadence/lib/tsmc025/signalstorm/osu025_stdcells.lib
"""
import re
import struct
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent
# INVX1 metal1 column x = 0.3..0.9 um; A pad y = 2.85..4.05; gnd strap ends at
# y = 2.4, vdd strap starts at y = 11.1.
STRAPS = {"TIEHI": (0.3, 2.4, 0.9, 2.85), "TIELO": (0.3, 4.05, 0.9, 11.1)}
VALUE = {"TIEHI": "1", "TIELO": "0"}
METAL1_GDS = 49  # MOSIS SCMOS GDS layer number
PIN_GDS = 81     # pin marker layer next to the A label in the upstream layout

HEADER, BGNLIB, LIBNAME, UNITS, ENDLIB = 0x00, 0x01, 0x02, 0x03, 0x04
BGNSTR, STRNAME, ENDSTR = 0x05, 0x06, 0x07
BOUNDARY, LAYER, DATATYPE, XY, ENDEL, STRING = 0x08, 0x0D, 0x0E, 0x10, 0x11, 0x19


def records(data):
    i = 0
    while i < len(data):
        n, rt = struct.unpack(">HB", data[i:i + 3])
        if n == 0:
            break
        yield rt, data[i:i + n]
        i += n


def rec(rt, dt, body):
    return struct.pack(">HBB", len(body) + 4, rt, dt) + body


def gds_string(s):
    b = s.encode()
    return b + b"\0" * (len(b) % 2)


def gds_real(b):
    sign = -1 if b[0] & 0x80 else 1
    mant = int.from_bytes(b[1:8], "big") / (1 << 56)
    return sign * mant * 16 ** ((b[0] & 0x7F) - 64)


def elements(recs):
    elem = []
    for rt, raw in recs:
        elem.append((rt, raw))
        if rt == ENDEL:
            yield elem
            elem = []


def is_a_pin(elem):
    """The upstream 'A' label and its pin marker, which a tie cell no longer has."""
    if any(rt == STRING and raw[4:].rstrip(b"\0") == b"A" for rt, raw in elem):
        return True
    layers = [struct.unpack(">h", raw[4:6])[0] for rt, raw in elem if rt == LAYER]
    xys = [struct.unpack(">10i", raw[4:44]) for rt, raw in elem if rt == XY and len(raw) == 44]
    return layers == [PIN_GDS] and bool(xys) and xys[0][:2] == (300, 3450)


def gds(src):
    recs = list(records(Path(src).read_bytes()))
    head = b"".join(raw for rt, raw in recs if rt in (HEADER, BGNLIB))
    units = next(raw for rt, raw in recs if rt == UNITS)
    dbu_per_um = 1e-6 / gds_real(units[12:20])
    invx1, inside = [], False
    for rt, raw in recs:
        if rt == BGNSTR:
            bgnstr = raw
        elif rt == STRNAME:
            inside = raw[4:].rstrip(b"\0") == b"INVX1"
        elif inside:
            if rt == ENDSTR:
                break
            invx1.append((rt, raw))
    if not invx1:
        sys.exit(f"{src}: INVX1 not found")
    out = [head, rec(LIBNAME, 0x06, gds_string("osu025_tie")), rec(UNITS, 0x05, units[4:])]
    for name, (x1, y1, x2, y2) in STRAPS.items():
        out += [bgnstr, rec(STRNAME, 0x06, gds_string(name))]
        out += [raw for elem in elements(invx1) if not is_a_pin(elem) for _, raw in elem]
        x1, y1, x2, y2 = (round(v * dbu_per_um) for v in (x1, y1, x2, y2))
        xy = struct.pack(">10i", x1, y1, x2, y1, x2, y2, x1, y2, x1, y1)
        out += [rec(BOUNDARY, 0x00, b""), rec(LAYER, 0x02, struct.pack(">h", METAL1_GDS)),
                rec(DATATYPE, 0x02, struct.pack(">h", 0)), rec(XY, 0x03, xy),
                rec(ENDEL, 0x00, b""), rec(ENDSTR, 0x00, b"")]
    out.append(rec(ENDLIB, 0x00, b""))
    (OUT / "osu025_tie.gds").write_bytes(b"".join(out))


def lef(src):
    text = Path(src).read_text()
    invx1 = re.search(r"^MACRO INVX1\n.*?^END INVX1\n", text, re.S | re.M).group(0)
    a_pin = re.search(r"  PIN A\n.*?  END A\n", invx1, re.S).group(0)
    a_rect = re.search(r"RECT [^;]*;", a_pin).group(0)
    out = ["# TIEHI/TIELO for osu025, generated by make_tie_cells.py from upstream INVX1.\n",
           "VERSION 5.4 ;\nNAMESCASESENSITIVE ON ;\nBUSBITCHARS \"[]\" ;\nDIVIDERCHAR \"/\" ;\n\n"]
    for name, (x1, y1, x2, y2) in STRAPS.items():
        rail = "gnd" if name == "TIEHI" else "vdd"
        body = invx1.replace(a_pin, "").replace("INVX1", name)
        # The input pad and the new strap become part of the rail pin.
        extra = f"        {a_rect}\n        RECT {x1:.3f} {y1:.3f} {x2:.3f} {y2:.3f} ;\n"
        body = re.sub(rf"(  PIN {rail}\n.*?LAYER metal1 ;\n)", lambda m: m.group(1) + extra,
                      body, count=1, flags=re.S)
        out.append(body + "\n")
    out.append("END LIBRARY\n")
    (OUT / "osu025_tie.lef").write_text("".join(out))


def lib(src):
    text = Path(src).read_text()
    leak = re.search(r"cell \(INVX1\) \{.*?cell_leakage_power : ([0-9.eE+-]+)", text, re.S).group(1)
    # Same units and operating conditions as the upstream library.
    header = re.search(r"library\(osu025_stdcells\) \{.*?default_operating_conditions : typical;\n",
                       text, re.S).group(0).replace("osu025_stdcells", "osu025_tie")
    cells = "".join(f"""
  cell ({name}) {{
    area : 36;
    cell_footprint : {name.lower()};
    cell_leakage_power : {leak};
    dont_touch : true;
    pin(Y) {{
      direction : output;
      function : "{VALUE[name]}";
    }}
  }}
""" for name in STRAPS)
    (OUT / "osu025_tie.lib").write_text(
        "/* TIEHI/TIELO for osu025, generated by make_tie_cells.py from upstream INVX1. */\n"
        + header + cells + "}\n")


def verilog():
    (OUT / "osu025_tie.v").write_text(
        "// TIEHI/TIELO for osu025, generated by make_tie_cells.py.\n"
        + "".join(f"\nmodule {n} (Y);\n  output Y;\n  assign Y = 1'b{VALUE[n]};\nendmodule\n"
                  for n in STRAPS))


if __name__ == "__main__":
    src_gds, src_lef, src_lib = sys.argv[1:4]
    gds(src_gds)
    lef(src_lef)
    lib(src_lib)
    verilog()
